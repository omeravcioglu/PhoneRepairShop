        private static Dictionary<char, string[]> lookup;

        /// <summary>Every glyph in code order, rows padded to the cell height.</summary>
        public static IEnumerable<(char code, string[] rows)> All
        {
            get
            {
                foreach ((char code, string _) in Table)
                {
                    yield return (code, Rows(code));
                }
            }
        }

        public static bool Has(char c) => Lookup.ContainsKey(c);

        /// <summary>Rows (top to bottom, <see cref="CellHeight"/> of them) of a glyph, or null.</summary>
        public static string[] Rows(char c) => Lookup.TryGetValue(c, out string[] rows) ? rows : null;

        public static int WidthOf(char c)
        {
            if (c == ' ')
            {
                return SpaceAdvance - LetterSpacing;
            }

            string[] rows = Rows(c) ?? Rows('?');
            return rows[0].Length;
        }

        public static int Advance(char c) => c == ' ' ? SpaceAdvance : WidthOf(c) + LetterSpacing;

        public static int MeasureText(string text)
        {
            int width = 0;
            int pen = 0;
            foreach (char c in text)
            {
                if (c == ' ')
                {
                    pen += SpaceAdvance;
                    continue;
                }

                width = pen + WidthOf(c);
                pen += Advance(c);
            }

            return width;
        }

        private static Dictionary<char, string[]> Lookup
        {
            get
            {
                if (lookup != null)
                {
                    return lookup;
                }

                lookup = new Dictionary<char, string[]>();
                foreach ((char code, string packed) in Table)
                {
                    string[] given = packed.Split('|');
                    int width = given[0].Length;
                    var rows = new string[CellHeight];
                    for (int r = 0; r < CellHeight; r++)
                    {
                        rows[r] = r < given.Length ? given[r] : new string('.', width);
                    }

                    lookup[code] = rows;
                }

                return lookup;
            }
        }
