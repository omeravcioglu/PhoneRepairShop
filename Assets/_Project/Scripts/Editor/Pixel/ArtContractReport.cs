using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using UnityEditor;
using UnityEngine;

namespace PhoneRepair.EditorTools
{
    /// <summary>
    /// Writes the art contract for humans: Docs/Art_Contract.md (every sprite with its size, pivot,
    /// frames, 9-slice and notes, plus the layout anchors and how much is still placeholder) and
    /// Docs/Images/S1/art_contact_sheet.png (every sprite at a glance). Generated from the JSON.
    /// </summary>
    internal static class ArtContractReport
    {
        public const string DocPath = "Docs/Art_Contract.md";
        public const string SheetPath = "Docs/Images/S1/art_contact_sheet.png";

        [MenuItem("Tools/Phone Repair/Art Contract Status", priority = 10)]
        public static void LogStatus()
        {
            PixelArtSetup.Status status = PixelArtSetup.Check(out List<string> placeholders, out List<string> missing);
            Debug.Log($"[PhoneRepair] Art: {status.Real} real, {status.Placeholders} placeholder, {status.Missing} missing.\n" +
                      (placeholders.Count > 0 ? "Still placeholder:\n  " + string.Join("\n  ", placeholders) : "No placeholders left."));
        }

        public static void Write()
        {
            ArtContractData data = ArtContract.Load();
            PixelArtSetup.Status status = PixelArtSetup.Check(out List<string> placeholders, out List<string> missing);
            var placeholderSet = new HashSet<string>(placeholders);

            var md = new StringBuilder();
            md.AppendLine("# Art contract: pixel art");
            md.AppendLine();
            md.AppendLine($"Generated by **Tools > Phone Repair > Run Setup** from `{ArtContract.JsonPath}`. Edit the JSON, not this file.");
            md.AppendLine();
            md.AppendLine($"**Status:** {status.Real} of {status.Real + status.Placeholders + status.Missing} files are real art; {status.Placeholders} are generated placeholders" +
                          (status.Missing > 0 ? $"; {status.Missing} are missing." : "."));
            md.AppendLine();
            md.AppendLine("![Every sprite at a glance](Images/S1/art_contact_sheet.png)");
            md.AppendLine();
            md.AppendLine("## Rules");
            md.AppendLine();
            foreach (string rule in data.rules ?? new string[0])
            {
                md.AppendLine($"- {rule}");
            }

            md.AppendLine();
            md.AppendLine("## Delivering art");
            md.AppendLine();
            md.AppendLine("1. Draw the sprite at exactly the size below (pixel art, 1 game pixel = 1 image pixel).");
            md.AppendLine($"2. Save it as PNG over the placeholder, same file name, under `{data.root}/`.");
            md.AppendLine("3. Run **Tools > Phone Repair > Run Setup**. Your file is never overwritten; the importer applies the pivot, 9-slice and pixel settings, and the prefab and scene pick the new art up.");
            md.AppendLine("4. **Tools > Phone Repair > Art Contract Status** lists what is still placeholder.");
            md.AppendLine();

            foreach (IGrouping<string, SpriteSpec> group in data.sprites.GroupBy(s => s.group ?? "Other"))
            {
                md.AppendLine($"## {group.Key}");
                md.AppendLine();
                md.AppendLine("| File(s) | Size | Pivot | Frames | 9-slice | On screen | Art | Notes |");
                md.AppendLine("|---|---|---|---|---|---|---|---|");
                foreach (SpriteSpec spec in group)
                {
                    string files = spec.FrameCount > 1 ? $"`{spec.file}_0..{spec.FrameCount - 1}.png`" : $"`{spec.file}.png`";
                    string slice = spec.Border == Vector4.zero ? "–" : $"{spec.border[0]},{spec.border[1]},{spec.border[2]},{spec.border[3]}";
                    string place = spec.place ? $"({spec.x}, {spec.y})" : "–";
                    bool allPlaceholder = Enumerable.Range(0, spec.FrameCount).All(f => placeholderSet.Contains(spec.FramePath(data.root, f)));
                    bool anyPlaceholder = Enumerable.Range(0, spec.FrameCount).Any(f => placeholderSet.Contains(spec.FramePath(data.root, f)));
                    string art = allPlaceholder ? "placeholder" : anyPlaceholder ? "partly" : "**done**";
                    string extras = (spec.outline ? " Needs 1 px transparent padding (hover outline)." : string.Empty);
                    md.AppendLine($"| {files} | {spec.w}×{spec.h} | {DescribePivot(spec)} | {spec.FrameCount} | {slice} | {place} | {art} | {Escape(spec.notes)}{extras} |");
                }

                md.AppendLine();
            }

            md.AppendLine("## Layout anchors");
            md.AppendLine();
            md.AppendLine("Named points the game uses for placement (world pixels: the shop view is y 0..360, the bench view y -360..0; `phone.*` are relative to the phone's centre).");
            md.AppendLine();
            md.AppendLine("| Anchor | x, y | What |");
            md.AppendLine("|---|---|---|");
            foreach (AnchorSpec anchor in data.anchors)
            {
                md.AppendLine($"| `{anchor.id}` | {anchor.x}, {anchor.y} | {Escape(anchor.notes)} |");
            }

            Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(DocPath))!);
            File.WriteAllText(Path.GetFullPath(DocPath), md.ToString());
            WriteContactSheet(data, placeholderSet);
            Debug.Log($"[PhoneRepair] Wrote {DocPath} and {SheetPath}.");
        }

        private static string DescribePivot(SpriteSpec spec) => (spec.pivot ?? "Center") switch
        {
            "BottomLeft" => "bottom-left",
            "BottomCenter" => "bottom-centre",
            "TopLeft" => "top-left",
            "Pixel" => $"pixel ({spec.px}, {spec.py})",
            _ => "centre",
        };

        private static string Escape(string text) => (text ?? string.Empty).Replace("|", "/").Replace("\n", " ");

        /// <summary>Every sprite (frame 0 and the other frames next to it) with its id, on one image.</summary>
        private static void WriteContactSheet(ArtContractData data, HashSet<string> placeholders)
        {
            const int sheetWidth = 1600;
            const int pad = 10;
            var items = new List<(string label, Color32[][] frames, int w, int h, int scale, bool placeholder)>();
            foreach (SpriteSpec spec in data.sprites)
            {
                var frames = new List<Color32[]>();
                int w = spec.w, h = spec.h;
                bool placeholder = true;
                for (int f = 0; f < spec.FrameCount; f++)
                {
                    string path = spec.FramePath(data.root, f);
                    placeholder &= placeholders.Contains(path);
                    Color32[] pixels = ReadPixels(path, out int fw, out int fh);
                    if (pixels != null)
                    {
                        frames.Add(pixels);
                        w = fw;
                        h = fh;
                    }
                }

                int scale = Mathf.Max(w, h) <= 24 ? 4 : Mathf.Max(w, h) <= 64 ? 3 : Mathf.Max(w, h) <= 200 ? 2 : 1;
                items.Add((spec.id, frames.ToArray(), w, h, scale, placeholder));
            }

            // flow layout
            var placements = new List<(int x, int y, int item)>();
            int cursorX = pad, rowTop = pad, rowHeight = 0;
            for (int i = 0; i < items.Count; i++)
            {
                var item = items[i];
                int width = Mathf.Max(PixelGlyphs.MeasureText(item.label) * 2, item.frames.Length * (item.w * item.scale + 4));
                int height = item.h * item.scale + 26;
                if (cursorX + width > sheetWidth - pad && cursorX > pad)
                {
                    cursorX = pad;
                    rowTop += rowHeight + pad;
                    rowHeight = 0;
                }

                placements.Add((cursorX, rowTop, i));
                cursorX += width + pad * 2;
                rowHeight = Mathf.Max(rowHeight, height);
            }

            int sheetHeight = rowTop + rowHeight + pad;
            var canvas = new PixelCanvas(sheetWidth, sheetHeight);
            canvas.Fill(0, 0, sheetWidth, sheetHeight, new Color32(232, 222, 205, 255));
            foreach ((int x, int yTop, int index) in placements)
            {
                var item = items[index];
                int top = sheetHeight - 1 - yTop;          // canvas origin is bottom-left
                canvas.Text(item.label, x, top, item.placeholder ? new Color32(110, 100, 90, 255) : new Color32(40, 120, 70, 255), 2);
                int imageTop = top - 22;
                for (int f = 0; f < item.frames.Length; f++)
                {
                    int ox = x + f * (item.w * item.scale + 4);
                    int oy = imageTop - item.h * item.scale + 1;
                    canvas.Fill(ox, oy, item.w * item.scale, item.h * item.scale, new Color32(214, 204, 188, 255));
                    Blit(canvas, item.frames[f], item.w, item.h, ox, oy, item.scale);
                }
            }

            string full = Path.GetFullPath(SheetPath);
            Directory.CreateDirectory(Path.GetDirectoryName(full)!);
            File.WriteAllBytes(full, canvas.EncodeToPng());
        }

        private static Color32[] ReadPixels(string assetPath, out int width, out int height)
        {
            width = height = 0;
            string full = Path.GetFullPath(assetPath);
            if (!File.Exists(full))
            {
                return null;
            }

            var texture = new Texture2D(2, 2, TextureFormat.RGBA32, false);
            try
            {
                if (!texture.LoadImage(File.ReadAllBytes(full)))
                {
                    return null;
                }

                width = texture.width;
                height = texture.height;
                return texture.GetPixels32();
            }
            finally
            {
                Object.DestroyImmediate(texture);
            }
        }

        private static void Blit(PixelCanvas canvas, Color32[] pixels, int w, int h, int ox, int oy, int scale)
        {
            for (int y = 0; y < h; y++)
            {
                for (int x = 0; x < w; x++)
                {
                    Color32 c = pixels[y * w + x];
                    if (c.a == 0)
                    {
                        continue;
                    }

                    canvas.Fill(ox + x * scale, oy + y * scale, scale, scale, c);
                }
            }
        }
    }
}
