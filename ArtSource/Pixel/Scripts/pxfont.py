LINE_H = 10
CAP_H = 7


def glyph(ch: str) -> list[str]:
    return SMALL.get(ch) or SMALL.get(ch.upper()) or SMALL["?"]


def measure(text: str, spacing: int = 1) -> int:
    if not text:
        return 0
    return sum(len(glyph(c)[0]) for c in text) + spacing * (len(text) - 1)


def text(cv: px.Canvas, x: int, y: int, s: str, colour, spacing: int = 1, shadow=None,
         outline=None) -> int:
    """Draw `s` with its cap line at row y (top of capitals). Returns the advance width.
    shadow: colour drawn 1 px below; outline: colour drawn around every glyph pixel (8-neighbourhood)."""
    if outline is not None:
        for dx in (-1, 0, 1):
            for dy in (-1, 0, 1):
                if dx or dy:
                    _draw(cv, x + dx, y + dy, s, outline, spacing)
    if shadow is not None:
        _draw(cv, x, y + 1, s, shadow, spacing)
    return _draw(cv, x, y, s, colour, spacing)


def _draw(cv: px.Canvas, x: int, y: int, s: str, colour, spacing: int) -> int:
    cx = x
    for ch in s:
        g = glyph(ch)
        for r, row in enumerate(g):
            for c, v in enumerate(row):
                if v == "#":
                    cv.put(cx + c, y + r, colour)
        cx += len(g[0]) + spacing
    return cx - x - spacing


def text_center(cv: px.Canvas, cx: int, y: int, s: str, colour, **kw) -> int:
    w = measure(s, kw.get("spacing", 1))
    return text(cv, cx - w // 2, y, s, colour, **kw)


def wrap(s: str, max_w: int) -> list[str]:
    words, lines, cur = s.split(" "), [], ""
    for w in words:
        trial = w if not cur else cur + " " + w
        if measure(trial) <= max_w:
            cur = trial
        else:
            if cur:
                lines.append(cur)
            cur = w
    if cur:
        lines.append(cur)
    return lines


def font_sheet(colour=(40, 55, 71, 255), bg=(255, 253, 248, 255)) -> px.Canvas:
    rows = [
        "ABCDEFGHIJKLMNOPQRSTUVWXYZ",
        "abcdefghijklmnopqrstuvwxyz",
        "0123456789 .,!?:;'\"-+=()[]/%&*#<>^_~",
        "¥ × · … ♥ ★ ♪ → °",
        "Have you tried rice? We have. It doesn't work.",
    ]
    w = max(measure(r) for r in rows) + 8
    cv = px.Canvas(w, len(rows) * (LINE_H + 2) + 6, bg)
    for i, r in enumerate(rows):
        text(cv, 4, 4 + i * (LINE_H + 2), r, colour)
    return cv


