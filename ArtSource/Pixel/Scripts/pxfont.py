def micro_width(s: str, spacing: int = 1) -> int:
    if not s:
        return 0
    return sum(len(MICRO.get(ch.upper(), MICRO["?"])[0]) for ch in s) + spacing * (len(s) - 1)


def micro(cv: px.Canvas, x: int, y: int, s: str, colour, spacing: int = 1) -> int:
    """3x5 caps text with its top at row y. Returns the width."""
    cx = x
    for ch in s:
        g = MICRO.get(ch.upper(), MICRO["?"])
        for r, row in enumerate(g):
            for c, v in enumerate(row):
                if v == "#":
                    cv.put(cx + c, y + r, colour)
        cx += len(g[0]) + spacing
    return cx - x - spacing


def micro_center(cv: px.Canvas, cx: int, y: int, s: str, colour, spacing: int = 1) -> int:
    return micro(cv, cx - micro_width(s, spacing) // 2, y, s, colour, spacing)
