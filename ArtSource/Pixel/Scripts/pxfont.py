def _expand(strokes: list, ox: float, oy: float, u: float) -> list[list[tuple[float, float]]]:
    out = []
    for s in strokes:
        pts: list[tuple[float, float]] = []
        for item in s:
            if isinstance(item, tuple) and item and item[0] == "arc":
                _, cx, cy, rx, ry, a0, a1 = item
                n = max(8, int(abs(a1 - a0) / 12))
                pts += px.arc_pts(ox + cx * u, oy + cy * u, rx * u, ry * u, a0, a1, n)
            else:
                pts.append((ox + item[0] * u, oy + item[1] * u))
        out.append(pts)
    return out


def stroke_width(s: str, cap_h: int, r: float, tracking: float = 1.0) -> int:
    u = (cap_h - 2 * r) / 6.0
    total = 0.0
    for ch in s:
        w, _ = STROKE.get(ch.upper(), STROKE["?"])
        total += w * u + 2 * r + tracking
    return int(round(total - tracking))


def stroke_text(w: int, h: int, x: float, y: float, s: str, cap_h: int, r: float, tracking: float = 1.0,
                per_letter: bool = False):
    """Mask of `s` set in the stroke face with the cap line at y. Returns (mask, letter_masks)."""
    u = (cap_h - 2 * r) / 6.0
    mask = px.empty(w, h)
    letters = []
    cx = x
    for ch in s:
        gw, strokes = STROKE.get(ch.upper(), STROKE["?"])
        m = px.empty(w, h)
        for pts in _expand(strokes, cx + r, y + r, u):
            m |= px.stroke(w, h, pts, r)
        mask |= m
        letters.append(m)
        cx += gw * u + 2 * r + tracking
    return (mask, letters) if per_letter else mask


