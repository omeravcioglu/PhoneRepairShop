def _g(*rows: str) -> list[str]:
    w = len(rows[0])
    rows = list(rows) + ["." * w] * (9 - len(rows))
    assert all(len(r) == w for r in rows), rows
    return rows


def _lc(*rows: str) -> list[str]:
    """Lowercase without ascender: rows given start at row 2 (x-height)."""
    w = len(rows[0])
    return _g(*(["." * w] * 2 + list(rows)))


